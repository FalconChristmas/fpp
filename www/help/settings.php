<h3>FPP Settings</h3>

<p>This page groups all of FPP's settings into tabs. Press F1 again while a specific tab is open to see help for that tab, or keep reading for an overview.</p>

<ul>
    <li><b>Playback</b> — How FPP plays sequences and where audio goes.</li>
    <li><b>Audio / Video</b> — Sound card, PipeWire graph, video output and related media settings.</li>
    <li><b>Localization</b> — Language, time zone and geographic location for sunrise and sunset.</li>
    <li><b>User Interface</b> — Theme, colors and which advanced controls are shown.</li>
    <li><b>Email, MQTT</b> — Remote notifications and integration with home automation.</li>
    <li><b>Privacy</b> — Whether anonymous statistics and crash reports are shared.</li>
    <li><b>Output, Logging, Services, Storage, System</b> — Channel data behavior, log detail, background services, disk partitions and general system preferences.</li>
</ul>

<h4>Searching</h4>

<p>The search box above the tabs finds a setting without knowing which tab it lives on. As you type, the tabs are replaced by a single list of matching settings grouped under their tab name; click a tab name to jump to that tab, or clear the box (or press Escape) to return to the tabs. Settings can be changed directly in the results.</p>

<p>By default the search looks at each setting's name, its internal setting name, the choices in its drop-down and the value typed into it. Tick <b>Include tooltip text</b> to also match the wording behind each setting's help icon &mdash; useful when you remember what a setting does but not what it is called. Only settings shown at your current UI Level are searched. The Storage tab is not covered by the search.</p>

<p><b>Tip:</b> Advanced tabs such as Developer appear only when the UI Level is set to Advanced or higher. You do not need to change them for a normal show — the defaults are safe.</p>
